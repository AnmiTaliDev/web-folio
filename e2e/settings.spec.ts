test('the interface appearance settings are applied at once, kept after a reload and reset', async ({ page }) => {
  await page.goto('/settings/appearance')
  const html = page.locator('html')
  await chip(page, 'Крупный').click()
  await chip(page, 'Компактно').click()
  await chip(page, 'Острые').click()
  await chip(page, 'Системный').first().click()
  await chip(page, 'Уменьшить').click()
  await chip(page, 'Тёмная').click()
  await page.locator('md-switch').click()
  await expect(html).toHaveAttribute('data-density', 'compact')
  await expect(html).toHaveAttribute('data-shape', 'sharp')
  expect(await html.evaluate((element) => element.style.getPropertyValue('--font-text'))).toBe('var(--stack-system)')
  await expect(html).toHaveAttribute('data-motion', 'reduced')
  expect(await html.evaluate((element) => element.style.getPropertyValue('--ui-scale'))).toBe('1.15')
  expect(await html.evaluate((element) => element.style.getPropertyValue('--md-sys-color-surface'))).toBe('#000000')

  await page.reload()
  await expect(html).toHaveAttribute('data-shape', 'sharp')
  expect(await html.evaluate((element) => element.style.getPropertyValue('--ui-scale'))).toBe('1.15')

  await page.getByRole('button', { name: /Сбросить оформление/ }).click()
  await expect(html).toHaveAttribute('data-shape', 'soft')
  await expect(html).toHaveAttribute('data-density', 'comfortable')
  expect(await html.evaluate((element) => element.style.getPropertyValue('--ui-scale'))).toBe('1')
})

test('fonts can be chosen for the whole interface and for single parts, with adjustable axes', async ({ page }) => {
  await page.goto('/settings/appearance')
  const html = page.locator('html')
  const variable = (name: string) => html.evaluate((element, key) => element.style.getPropertyValue(key), name)
  await chip(page, 'Google Sans Flex (расширенный)').first().click()
  expect(await variable('--font-text')).toBe('var(--stack-google-sans-flex)')
  expect(await variable('--font-headings')).toBe('var(--stack-google-sans-flex)')
  await expect(page.locator('md-slider')).toHaveCount(4)
  expect(await variable('--fv-text')).toBe("'wdth' 100, 'ROND' 0, 'slnt' 0")

  await page.locator('details summary').click()
  const headings = page.locator('details').getByRole('radiogroup', { name: 'Заголовки' })
  await headings.locator('md-filter-chip').filter({ hasText: /^\s*С засечками\s*$/ }).click()
  expect(await variable('--font-headings')).toBe('var(--stack-serif)')
  expect(await variable('--font-text')).toBe('var(--stack-google-sans-flex)')

  await page.getByRole('button', { name: /Сбросить оформление/ }).click()
  expect(await variable('--font-headings')).toBe('var(--stack-roboto-flex)')
  await expect(page.locator('md-slider')).toHaveCount(0)
})
